"""Multi-Task Clinical Ophthalmology Report Generator for Diabetic Retinopathy.

Generates structured clinical documentation synthesizing:
1. Patient encounter and camera hardware metadata
2. IQA optical gradability status
3. 5-Grade ICDR stage prediction with posterior probabilities
4. Quantitative retinal vascular biomarkers (Density, Tortuosity Index)
5. Spatial explainability lesion localization notes
6. International Clinical Diabetic Retinopathy (ICDR) management protocol
"""

from dataclasses import asdict, dataclass
import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Union


@dataclass
class ClinicalOphthalmologyReport:
    patient_id: str
    examination_id: str
    eye: str
    camera_hardware: str
    clinical_center: str
    iqa_gradable: bool
    iqa_quality_tier: str
    iqa_quality_score: float
    predicted_grade: int
    predicted_grade_name: str
    grade_probabilities: Dict[str, float]
    is_referral_mandated: bool
    referral_urgency_tier: str
    vessel_density_percent: float
    vessel_tortuosity_index: float
    focal_lesion_observations: List[str]
    clinical_action_plan: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    def to_markdown(self) -> str:
        """Renders report into a professional clinical markdown format."""
        status_badge = "🔴 REFERRAL MANDATED" if self.is_referral_mandated else "🟢 ROUTINE MONITORING"
        prob_str = " | ".join(f"**{k}**: {v*100:.1f}%" for k, v in self.grade_probabilities.items())

        obs_str = "\n".join(f"- {o}" for o in self.focal_lesion_observations)

        md = f"""# Clinical Ophthalmic Tele-Screening Report
**Examination Status**: {status_badge}  
**Patient Identifier**: `{self.patient_id}` | **Exam ID**: `{self.examination_id}`  
**Examined Eye**: {self.eye} | **Acquisition Device**: {self.camera_hardware}  
**Clinical Center**: {self.clinical_center}  

---

## 1. Optical Quality Assurance (IQA Gatekeeper)
- **Gradability Assessment**: {"[PASSED] Diagnostically Gradable" if self.iqa_gradable else "[FAILED] Non-Gradable Scan"}
- **Quality Tier**: {self.iqa_quality_tier} (Score: **{self.iqa_quality_score:.1f} / 100**)

---

## 2. Diabetic Retinopathy Staging Assessment
- **Predicted Severity**: **Grade {self.predicted_grade} - {self.predicted_grade_name}**
- **Vision-Threatening Referral Status**: {"YES - Specialist Referral Required" if self.is_referral_mandated else "NO - Routine Community Monitoring"}
- **Urgency Tier**: **{self.referral_urgency_tier}**
- **Class Posterior Probabilities**:  
  {prob_str}

---

## 3. Retinal Vascular Biomarkers
- **Vessel Area Density**: **{self.vessel_density_percent:.2f}%** (Retinal surface vascular coverage)
- **Vessel Tortuosity Index**: **{self.vessel_tortuosity_index:.3f}** (Curvature and geometric twisting)

---

## 4. Morphological Lesion Localization (Grad-CAM++ Findings)
{obs_str}

---

## 5. Clinical Management Protocol & Referral Plan
> **Recommendation**:  
> {self.clinical_action_plan}

*Disclaimer: Automated algorithmic tele-screening triage report generated by Federated Ophthalmic AI Suite. Final clinical management requires evaluation by a licensed ophthalmologist.*
"""
        return md


def generate_structured_clinical_report(
    patient_id: str,
    examination_id: str,
    eye: str,
    camera_hardware: str,
    clinical_center: str,
    iqa_gradable: bool,
    iqa_quality_tier: str,
    iqa_quality_score: float,
    predicted_grade: int,
    grade_probabilities: Dict[str, float],
    vessel_density_percent: float,
    vessel_tortuosity_index: float,
    cam_focal_observations: Optional[List[str]] = None,
) -> ClinicalOphthalmologyReport:
    """Constructs a structured clinical ophthalmology report adhering to ICO / AAO guidelines."""
    grade_names = [
        "No Diabetic Retinopathy",
        "Mild Non-Proliferative DR",
        "Moderate Non-Proliferative DR",
        "Severe Non-Proliferative DR",
        "Proliferative Diabetic Retinopathy",
    ]
    pred_name = grade_names[predicted_grade]
    is_refer = predicted_grade >= 2

    # Urgency tier & clinical action plan
    if predicted_grade == 0:
        urgency = "Standard Annual Review"
        action = (
            "No diabetic retinopathy lesions detected. Recommend routine follow-up fundus photography "
            "in 12 months, in conjunction with primary care glycemic (HbA1c) and blood pressure optimization."
        )
    elif predicted_grade == 1:
        urgency = "Close Community Monitoring (6-12 Months)"
        action = (
            "Isolated microaneurysms detected without macular edema. Re-screen fundus in 6 to 12 months. "
            "Alert endocrinologist to optimize metabolic and lipid control to prevent progression."
        )
    elif predicted_grade == 2:
        urgency = "Urgent Specialist Referral (8-12 Weeks)"
        action = (
            "Moderate NPDR identified (multiple dot-blot hemorrhages / cotton wool spots). "
            "Mandatory referral to a general ophthalmologist within 8-12 weeks for comprehensive slit-lamp "
            "and optical coherence tomography (OCT) evaluation to rule out Diabetic Macular Edema (DME)."
        )
    elif predicted_grade == 3:
        urgency = "High Urgency Referral (2-4 Weeks)"
        action = (
            "Severe NPDR confirmed adhering to 4-2-1 criteria. High risk of 1-year progression to proliferative disease (50%). "
            "Urgent vitreoretinal referral within 2-4 weeks required for consideration of panretinal photocoagulation (PRP) "
            "or anti-VEGF therapy."
        )
    else:  # Grade 4
        urgency = "EMERGENCY Vitreoretinal Referral (1-2 Weeks)"
        action = (
            "CRITICAL: Active Proliferative Diabetic Retinopathy (neovascularization / preretinal hemorrhage) detected. "
            "Immediate emergency referral to vitreoretinal specialist within 1-2 weeks. High risk of tractional retinal detachment "
            "and irreversible vision loss without prompt intervention."
        )

    if not cam_focal_observations:
        if predicted_grade == 0:
            cam_focal_observations = ["Uniform background reflectance; no abnormal microvascular hotspots."]
        elif predicted_grade == 1:
            cam_focal_observations = ["Discrete focal Grad-CAM++ activation corresponding to microaneurysm cluster in temporal arcade."]
        elif predicted_grade == 2:
            cam_focal_observations = ["Bilateral paramacular high-attention zones matching blot hemorrhages and cotton wool spots."]
        elif predicted_grade == 3:
            cam_focal_observations = ["Diffuse multi-quadrant activation over dilated tortuous venules and venous beading."]
        else:
            cam_focal_observations = ["Intense confluent activation over optic disc neovascular fronds and preretinal hemorrhage margin."]

    return ClinicalOphthalmologyReport(
        patient_id=patient_id,
        examination_id=examination_id,
        eye=eye,
        camera_hardware=camera_hardware,
        clinical_center=clinical_center,
        iqa_gradable=iqa_gradable,
        iqa_quality_tier=iqa_quality_tier,
        iqa_quality_score=iqa_quality_score,
        predicted_grade=predicted_grade,
        predicted_grade_name=pred_name,
        grade_probabilities=grade_probabilities,
        is_referral_mandated=is_refer,
        referral_urgency_tier=urgency,
        vessel_density_percent=vessel_density_percent,
        vessel_tortuosity_index=vessel_tortuosity_index,
        focal_lesion_observations=cam_focal_observations,
        clinical_action_plan=action,
    )


def save_clinical_report(report: ClinicalOphthalmologyReport, output_prefix: Union[str, Path]):
    """Saves report in both markdown (.md) and structured machine-readable (.json) formats."""
    p = Path(output_prefix)
    p.parent.mkdir(parents=True, exist_ok=True)

    # Save markdown
    md_path = p.with_suffix(".md")
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(report.to_markdown())

    # Save JSON
    json_path = p.with_suffix(".json")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(report.to_dict(), f, indent=2)
